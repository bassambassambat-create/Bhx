document.querySelector('#save-quran-progress').addEventListener('click', () => {
  if (!loadedAyahs) return;
  const surah = Number(quranSelect.value);
  const start = Number(document.querySelector('#ayah-start').value);
  const end = Number(document.querySelector('#ayah-end').value);
  const range = `${surah}:${start}-${end}`;
  if (!quranProgress.includes(range)) quranProgress.push(range);
  try { localStorage.setItem(QURAN_PROGRESS_KEY, JSON.stringify(quranProgress)); }
  catch { document.querySelector('#recitation-status').textContent += ' تعذر حفظ التقدم في هذا المتصفح.'; }
  renderQuranProgress();
  document.querySelector('#recitation-status').textContent += ' حفظت أنك راجعت هذا المقطع؛ راجع المصحف أو معلّمك لتأكيد التلاوة.';
});

