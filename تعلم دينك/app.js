const duaSearch = document.querySelector('#dua-search');
const duaSourceFilter = document.querySelector('#dua-source-filter');
const duaResults = document.querySelector('#dua-results');
const duaCount = document.querySelector('#dua-count');
function renderDuas() {
  const query = normalizeArabic(duaSearch.value);
  const sourceFilter = duaSourceFilter.value;
  const results = duaLibrary.filter((dua) => (sourceFilter === 'all' || dua.sourceType === sourceFilter)
    && normalizeArabic([dua.text, dua.meaning, dua.when, dua.source].join(' ')).includes(query));
  duaCount.textContent = `ظهرت ${new Intl.NumberFormat('ar-SA').format(results.length)} من ${new Intl.NumberFormat('ar-SA').format(duaLibrary.length)} دعاءً في المجموعة.`;
  duaResults.replaceChildren();
  if (!results.length) {
    const empty = document.createElement('p');
    empty.className = 'hadith-empty';
    empty.textContent = 'ما لقيت دعاءً بهذا البحث في المجموعة. جرّب كلمة أبسط.';
    duaResults.append(empty);
    return;
  }
  results.forEach((dua) => {
    const card = document.createElement('article');
    card.className = 'dua-card';
    const sourceType = document.createElement('span');
    sourceType.className = 'hadith-topic';
    sourceType.textContent = dua.sourceType === 'quran' ? 'من القرآن' : 'من السنة';
    const text = document.createElement('p');
    text.className = 'dua-text';
    text.textContent = `﴿ ${dua.text} ﴾`;
    const meaning = document.createElement('p');
    meaning.className = 'hadith-note';
    meaning.textContent = `المعنى: ${dua.meaning}`;
    const when = document.createElement('p');
    when.className = 'hadith-details';
    when.textContent = `متى يقال؟ ${dua.when}`;
    const source = document.createElement('p');
    source.className = 'hadith-details';
    source.textContent = `المصدر: ${dua.source}`;
    card.append(sourceType, text, meaning, when, source);
    duaResults.append(card);
  });
}
duaSearch.addEventListener('input', renderDuas);
duaSourceFilter.addEventListener('change', renderDuas);
renderDuas();

