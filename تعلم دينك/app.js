function normalizeArabic(value) {
  return value.toLocaleLowerCase('ar').replace(/[أإآٱ]/g, 'ا').replace(/[ى]/g, 'ي')
    .replace(/[\u064B-\u065F\u0670\u06D6-\u06EDـ]/g, '')
    .replace(/[٠-٩]/g, (digit) => String('٠١٢٣٤٥٦٧٨٩'.indexOf(digit))).trim();
}

