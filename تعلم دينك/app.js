async function loadPrayerTimes() {
  const requestId = ++prayerRequestId;
  prayerLoading = true;
  const city = document.querySelector('#prayer-city').value.trim();
  const country = document.querySelector('#prayer-country').value.trim();
  const method = document.querySelector('#prayer-method').value;
  if (prayerLocation.kind === 'city' && (!city || !country)) { prayerLoading = false; return; }
  const date = prayerTimeZoneDate();
  const status = document.querySelector('#prayer-times-status');
  status.textContent = 'أحمّل مواقيت الصلاة لهذا اليوم…';
  try {
    const base = prayerLocation.kind === 'coords'
      ? `https://api.aladhan.com/v1/timings/${date}?latitude=${prayerLocation.latitude}&longitude=${prayerLocation.longitude}`
      : `https://api.aladhan.com/v1/timingsByCity/${date}?city=${encodeURIComponent(city)}&country=${encodeURIComponent(country)}`;
    const response = await fetch(`${base}&method=${method}&calendarMethod=UAQ`);
    if (!response.ok) throw new Error('network');
    const payload = await response.json();
    if (requestId !== prayerRequestId) return;
    if (payload.code !== 200 || !payload.data?.timings) throw new Error('not-found');
    prayerTimesData = payload.data.timings;
    const returnedTimeZone = payload.data.meta?.timezone || prayerTimeZone;
    if (returnedTimeZone !== prayerTimeZone) {
      prayerTimeZone = returnedTimeZone;
      if (prayerTimeZoneDate() !== date) {
        prayerLoading = false;
        loadPrayerTimes();
        return;
      }
    }
    prayerDataDate = date;
    const day = new Intl.DateTimeFormat('ar-SA', { dateStyle: 'full', timeZone: prayerTimeZone }).format(new Date());
    const locationLabel = prayerLocation.kind === 'city' ? `${city}، ${country}` : prayerLocation.label;
    status.textContent = `مواقيت ${day} · ${locationLabel} · ${prayerMethodNames[method] || 'طريقة الحساب المختارة'}`;
    const list = document.querySelector('#prayer-times-list');
    list.replaceChildren();
    Object.entries(prayerNames).forEach(([key, name]) => {
      const item = document.createElement('div');
      item.className = 'prayer-time-item';
      const prayerName = document.createElement('span');
      prayerName.textContent = name;
      const time = document.createElement('strong');
      time.textContent = formatPrayerTime(prayerTimesData[key]);
      item.append(prayerName, time);
      list.append(item);
    });
    document.querySelector('#next-prayer-card').hidden = false;
    updateNextPrayer();
  } catch {
    if (requestId === prayerRequestId) status.textContent = 'ما قدرت أجيب الأوقات الآن. تحقق من اسم المدينة والدولة واتصال الإنترنت، أو جرّب استخدام موقعك.';
  } finally {
    if (requestId === prayerRequestId) prayerLoading = false;
  }
}
function getZonedClock() {
  const parts = new Intl.DateTimeFormat('en-GB', { timeZone: prayerTimeZone, hour: '2-digit', minute: '2-digit', second: '2-digit', hourCycle: 'h23' }).formatToParts(new Date());
  return Object.fromEntries(parts.map((part) => [part.type, Number(part.value)]));
}
function updateNextPrayer() {
  if (!prayerTimesData) return;
  const clock = getZonedClock();
  const nowSeconds = clock.hour * 3600 + clock.minute * 60 + clock.second;
  let next = null;
  for (const key of Object.keys(prayerNames)) {
    const match = String(prayerTimesData[key] || '').match(/(\d{1,2}):(\d{2})/);
    if (!match) continue;
    const seconds = Number(match[1]) * 3600 + Number(match[2]) * 60;
    if (seconds > nowSeconds) { next = { key, seconds, remaining: seconds - nowSeconds }; break; }
  }
  if (!next) {
    const fajr = String(prayerTimesData.Fajr || '').match(/(\d{1,2}):(\d{2})/);
    next = fajr ? { key: 'Fajr', remaining: 86400 + Number(fajr[1]) * 3600 + Number(fajr[2]) * 60 - nowSeconds } : null;
  }
  if (!next) return;
  const remaining = Math.max(0, next.remaining);
  const hours = Math.floor(remaining / 3600);
  const minutes = Math.floor((remaining % 3600) / 60);
  const seconds = remaining % 60;
  document.querySelector('#next-prayer-name').textContent = prayerNames[next.key];
  document.querySelector('#next-prayer-countdown').textContent = `بعد ${new Intl.NumberFormat('ar-SA').format(hours)}:${String(minutes).padStart(2, '0')}:${String(seconds).padStart(2, '0')}`;
}
