function loadLessons() {
  try {
    const current = JSON.parse(localStorage.getItem(STORAGE_KEY) || '[]');
    if (Array.isArray(current) && current.length) return current.filter((item) => item && typeof item.id === 'string' && typeof item.lesson === 'string');
    const oldLessons = JSON.parse(localStorage.getItem(OLD_LESSON_KEY) || '[]');
    if (Array.isArray(oldLessons) && oldLessons.length) {
      const migrated = oldLessons.filter((item) => item && typeof item.lesson === 'string').map((item, index) => ({
        id: item.id || `restored-${index}-${Date.now()}`,
        grade: item.grade || 'أول ابتدائي', subject: item.subject || 'أخرى', lesson: item.lesson,
        notes: item.notes || '', done: Boolean(item.done),
      }));
      if (migrated.length) return migrated;
    }
    const oldTasks = JSON.parse(localStorage.getItem(OLD_TASK_KEY) || '[]');
    if (Array.isArray(oldTasks)) return oldTasks.filter((item) => item && typeof item.title === 'string').map((item, index) => ({
      id: item.id || `restored-task-${index}-${Date.now()}`,
      grade: 'أول ابتدائي', subject: item.subject || 'أخرى', lesson: item.title,
      notes: item.dueDate ? `موعد التسليم: ${item.dueDate}` : '', done: Boolean(item.done),
    }));
    return [];
  } catch { return []; }
}
let lessons = loadLessons();
function save() {
  try { localStorage.setItem(STORAGE_KEY, JSON.stringify(lessons)); return true; }
  catch { return false; }
}
function saveDraft() {
  try {
    localStorage.setItem(DRAFT_KEY, JSON.stringify({
      grade: document.querySelector('#grade').value,
      subject: document.querySelector('#subject').value,
      lesson: document.querySelector('#lesson').value,
      notes: document.querySelector('#notes').value,
    }));
  } catch { /* Local file previews may block browser storage. */ }
}
function restoreDraft() {
  try {
    const draft = JSON.parse(localStorage.getItem(DRAFT_KEY) || 'null');
    if (!draft) return;
    if (draft.grade) document.querySelector('#grade').value = draft.grade;
    if (draft.subject && [...document.querySelector('#subject').options].some((option) => option.value === draft.subject)) {
      document.querySelector('#subject').value = draft.subject;
    } else document.querySelector('#subject').value = 'القرآن الكريم';
    if (draft.lesson) document.querySelector('#lesson').value = draft.lesson;
    if (draft.notes) document.querySelector('#notes').value = draft.notes;
  } catch { /* Ignore unavailable or malformed browser storage. */ }
}
function tell(message) {
  toast.textContent = message;
  toast.classList.add('show');
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => toast.classList.remove('show'), 2200);
}

