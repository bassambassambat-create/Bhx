const hadithCount = document.querySelector('#hadith-count');
function renderHadiths(query = '') {
  const normalizedQuery = normalizeArabic(query);
  const matches = hadithLibrary.filter((hadith) => normalizeArabic([
    hadith.text, hadith.narrator, hadith.grade, hadith.source, hadith.topic, hadith.note,
  ].join(' ')).includes(normalizedQuery));
  hadithCount.textContent = normalizedQuery
    ? `ظهرت ${new Intl.NumberFormat('ar-SA').format(matches.length)} نتيجة من الأحاديث المختارة.`
    : `مجموعة مختارة: ${new Intl.NumberFormat('ar-SA').format(hadithLibrary.length)} حديثًا.`;
  hadithResults.replaceChildren();
  if (!matches.length) {
    const empty = document.createElement('p');
    empty.className = 'hadith-empty';
    empty.textContent = 'ما لقيت هذا النص في المجموعة المختارة. استخدم البحث في الموسوعة الحديثية أدناه للتحقق من الأحاديث المتداولة.';
    hadithResults.append(empty);
    return;
  }
  matches.forEach((hadith) => {
    const card = document.createElement('article');
    card.className = 'hadith-card';
    const topic = document.createElement('span');
    topic.className = 'hadith-topic';
    topic.textContent = hadith.topic;
    const quote = document.createElement('blockquote');
    quote.textContent = `«${hadith.text}»`;
    const note = document.createElement('p');
    note.className = 'hadith-note';
    note.textContent = hadith.note;
    const details = document.createElement('p');
    details.className = 'hadith-details';
    details.textContent = `الراوي: ${hadith.narrator} · ${hadith.grade} · ${hadith.source}`;
    const verify = document.createElement('a');
    verify.href = `https://dorar.net/hadith/search?st=w&q=${encodeURIComponent(hadith.text)}`;
    verify.target = '_blank';
    verify.rel = 'noopener noreferrer';
    verify.textContent = 'تحقق من التخريج والحكم';
    const listen = document.createElement('button');
    listen.type = 'button';
    listen.className = 'secondary-button hadith-listen-button';
    listen.textContent = '▶ استمع إلى الحديث';
    listen.addEventListener('click', () => {
      const trackNumber = hadithLibrary.indexOf(hadith) + 1;
      hadithReaderAudio = `assets/narration/hadith_${String(trackNumber).padStart(2, '0')}.mp3`;
      hadithReaderLabel = `حديث ${hadith.topic}`;
      startNarration(hadithReaderAudio, hadithReaderLabel);
    });
    card.append(topic, quote, note, details, listen, verify);
    hadithResults.append(card);
  });
}
hadithSearch.addEventListener('input', () => renderHadiths(hadithSearch.value));
