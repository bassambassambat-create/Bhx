async function loadWordTimings(surahNumber) {
  wordTimingsByAyah = new Map();
  const slug = timingReciterSlugs[document.querySelector('#qari-select').value];
  if (!slug) return;
  try {
    const response = await fetch(`https://cdn.jsdelivr.net/gh/spa5k/quran-timings-api@main/data/api/reciters/${slug}/surahs/${surahNumber}/timings.json`);
    if (!response.ok) return;
    const data = await response.json();
    if (!Array.isArray(data.words)) return;
    data.words.forEach((word) => {
      const list = wordTimingsByAyah.get(Number(word.ayah)) || [];
      list.push(word);
      wordTimingsByAyah.set(Number(word.ayah), list);
    });
  } catch { wordTimingsByAyah = new Map(); }
}
