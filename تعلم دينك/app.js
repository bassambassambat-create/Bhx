function formatAudioTime(seconds) {
  if (!Number.isFinite(seconds) || seconds < 0) return '—:——';
  const whole = Math.floor(seconds);
  return `${Math.floor(whole / 60)}:${String(whole % 60).padStart(2, '0')}`;
}
function updateCombinedPlayer() {
  const complete = audioDurations.length === audioQueue.length && audioDurations.every(Number.isFinite);
  const elapsedBefore = audioDurations.slice(0, audioQueueIndex).reduce((sum, duration) => sum + (Number.isFinite(duration) ? duration : 0), 0);
  const elapsed = elapsedBefore + (Number.isFinite(quranAudio.currentTime) ? quranAudio.currentTime : 0);
  const total = complete ? audioDurations.reduce((sum, duration) => sum + duration, 0) : null;
  if (complete) {
    audioSeek.max = String(total);
    audioSeek.value = String(Math.min(elapsed, total));
    audioSeek.disabled = false;
    audioTime.textContent = `${formatAudioTime(elapsed)} / ${formatAudioTime(total)}`;
  } else {
    audioSeek.max = '0';
    audioSeek.value = '0';
    audioSeek.disabled = true;
    audioTime.textContent = `${formatAudioTime(elapsed)} / جارٍ حساب المدة الكاملة…`;
  }
}
async function measureAudioQueue() {
  const urls = [...audioQueue];
  durationScanId += 1;
  const scanId = durationScanId;
  audioDurations = Array(urls.length).fill(null);
  updateCombinedPlayer();
  let next = 0;
  const workers = Array.from({ length: Math.min(6, urls.length) }, async () => {
    while (next < urls.length) {
      const index = next++;
      const duration = await new Promise((resolve) => {
        const probe = new Audio();
        const finish = (duration) => { probe.removeAttribute('src'); resolve(duration); };
        const timeout = setTimeout(() => finish(null), 20000);
        probe.preload = 'metadata';
        probe.addEventListener('loadedmetadata', () => { clearTimeout(timeout); finish(probe.duration); }, { once: true });
        probe.addEventListener('error', () => { clearTimeout(timeout); finish(null); }, { once: true });
        probe.src = urls[index];
        probe.load();
      });
      if (scanId !== durationScanId) return;
      audioDurations[index] = duration;
      updateCombinedPlayer();
    }
  });
  await Promise.all(workers);
  if (scanId === durationScanId) updateCombinedPlayer();
}
