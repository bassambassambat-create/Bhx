function runSiteSearch(query) {
  const normalized = normalizeArabic(query);
  siteSearchResults.replaceChildren();
  const results = normalized ? siteSearchCategories.filter((category) => category.words.some((word) => normalized.includes(word) || (normalized.length > 2 && word.includes(normalized)))) : siteSearchCategories;
  results.forEach((result) => {
    if (result.id) result.action = () => {
      const topic = document.getElementById(result.id);
      topic.scrollIntoView({ behavior: 'smooth', block: 'center' });
    };
  });
  if (normalized) prophetStories.forEach((prophet) => {
    const name = normalizeArabic(prophet.name);
    if (normalized.includes(name) || (normalized.length > 1 && name.includes(normalized))) {
      results.push({ type: 'قصة نبي', title: prophet.target ? 'السيرة النبوية للنبي محمد ﷺ' : `قصة النبي ${prophet.name} عليه السلام`, subtitle: `في القرآن: ${prophet.sources}`, action: () => showProphetStory(prophet) });
    }
  });
  if (normalized) quranSurahs.forEach((name, index) => {
    if (normalizeArabic(name).includes(normalized)) results.push({ type: 'سورة من القرآن', title: `سورة ${name}`, action: () => { quranSelect.value = String(index + 1); quranSelect.dispatchEvent(new Event('change')); document.querySelector('#quran-panel').scrollIntoView({ behavior: 'smooth' }); } });
  });
  if (normalized) hadithLibrary.forEach((hadith) => {
    if (normalizeArabic([hadith.text, hadith.topic, hadith.note].join(' ')).includes(normalized)) results.push({ type: 'حديث', title: hadith.topic, subtitle: hadith.text, action: () => { hadithSearch.value = hadith.text; renderHadiths(hadith.text); document.querySelector('#hadith-section').scrollIntoView({ behavior: 'smooth' }); } });
  });
  if (normalized) duaLibrary.forEach((dua) => {
    if (normalizeArabic([dua.text, dua.meaning, dua.when].join(' ')).includes(normalized)) results.push({ type: 'دعاء', title: dua.when, subtitle: dua.text, action: () => { duaSearch.value = dua.text; duaSourceFilter.value = 'all'; renderDuas(); document.querySelector('#duas-section').scrollIntoView({ behavior: 'smooth' }); } });
  });
  results.slice(0, 15).forEach((result) => {
    const button = document.createElement('button');
    button.type = 'button';
    button.className = 'site-search-result';
    button.setAttribute('role', 'option');
    const type = document.createElement('small');
    type.textContent = result.type;
    const title = document.createElement('strong');
    title.textContent = result.title;
    button.append(type, title);
    if (result.subtitle) {
      const subtitle = document.createElement('span');
      subtitle.textContent = result.subtitle;
      button.append(subtitle);
    }
    button.addEventListener('click', () => { result.action(); closeSiteSearch(); siteSearchInput.value = ''; });
    siteSearchResults.append(button);
  });
  if (!results.length) {
    const empty = document.createElement('p');
    empty.className = 'site-search-empty';
    empty.textContent = 'ما لقيت نتيجة في المجموعة الحالية. جرّب كلمة أخرى.';
    siteSearchResults.append(empty);
  }
  siteSearchResults.hidden = false;
  siteSearchInput.setAttribute('aria-expanded', 'true');
}
