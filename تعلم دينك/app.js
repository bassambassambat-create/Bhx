function findTopic(text) {
  const normalized = normalizeArabic(text);
  const canonicalSurah = quranSurahs.find((name) => normalized.includes(`سورة ${normalizeArabic(name)}`) || normalized === normalizeArabic(name));
  const aliasSurah = Object.entries(surahAliases).find(([alias]) => normalized.includes(`سورة ${normalizeArabic(alias)}`) || normalized === normalizeArabic(alias))?.[1];
  const surahName = canonicalSurah || aliasSurah;
  if (surahName) {
    const surahIndex = quranSurahs.findIndex((name) => normalizeArabic(name) === normalizeArabic(surahName));
    if (surahIndex >= 0) return makeSurahTopic(quranSurahs[surahIndex], surahIndex);
  }
  const faithKeywords = ['القرآن', 'آية', 'الله', 'الحديث', 'السنة', 'النبي', 'محمد', 'الإسلام', 'الإيمان', 'التوحيد', 'العقيدة', 'الصلاة', 'الوضوء', 'الزكاة', 'الصيام', 'الصوم', 'الحج', 'العمرة', 'الفقه', 'السيرة', 'الصدق', 'الأمانة', 'الأخلاق', 'الآداب', 'الدعاء', 'الأذكار', 'الاستغفار', 'بر الوالدين', 'صلة الرحم', 'الرحمة', 'الصبر', 'الشكر', 'الإحسان', 'الجنة', 'النار', 'الملائكة', 'الرسل', 'الأنبياء', 'الطهارة', 'المسجد', 'الجمعة', 'العيد', 'الشهادة', 'الأذان'];
  return topics.find((topic) => topic.keys.some((key) => {
    const keyText = normalizeArabic(key);
    return normalized.includes(keyText) && faithKeywords.some((keyword) => {
      const faithText = normalizeArabic(keyword);
      return keyText.includes(faithText) || faithText.includes(keyText);
    });
  }));
}

