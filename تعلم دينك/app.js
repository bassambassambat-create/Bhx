function highlightCurrentWord(preserveWordOnResume = false) {
  if (activeQuranAudio.paused) return;
  const repeatCount = Number(document.querySelector('#ayah-repeat').value) || 1;
  const ayah = loadedAyahs?.[Math.floor(audioQueueIndex / repeatCount)];
  const words = wordTimingsByAyah.get(ayah?.number) || [];
  const now = activeQuranAudio.currentTime;
  const timing = words.find((word) => now >= Number(word.start_s) && now < Number(word.end_s));
  const ayahWordElements = [...document.querySelectorAll(`.ayah-line[data-ayah="${ayah?.number}"] .word-token`)];
  let activeIndex = timing ? Number(timing.word_index_in_ayah) : -1;
  if (!words.length && Number.isFinite(activeQuranAudio.duration) && activeQuranAudio.duration > 0) {
    const weights = ayahWordElements.map((word) => Math.max(1, [...word.textContent].filter((char) => /[\u0600-\u06FF]/.test(char)).length));
    const totalWeight = weights.reduce((sum, weight) => sum + weight, 0);
    const progress = Math.min(0.999, Math.max(0, now / activeQuranAudio.duration));
    let elapsedWeight = 0;
    activeIndex = weights.findIndex((weight) => {
      elapsedWeight += weight;
      return progress * totalWeight < elapsedWeight;
    }) + 1;
  }
  if (preserveWordOnResume && !timing && !words.length && !Number.isFinite(activeQuranAudio.duration)) return;
  document.querySelectorAll('#ayah-text-display .word-token').forEach((word) => {
    const active = Number(word.dataset.word) === activeIndex && Number(word.closest('.ayah-line')?.dataset.ayah) === ayah?.number;
    const lineAyah = Number(word.closest('.ayah-line')?.dataset.ayah);
    const wordTiming = (wordTimingsByAyah.get(lineAyah) || []).find((item) => Number(item.word_index_in_ayah) === Number(word.dataset.word));
    const spoken = lineAyah === ayah?.number && (wordTiming
      ? now >= Number(wordTiming.start_s)
      : activeIndex > 0 && Number(word.dataset.word) <= activeIndex);
    if (spoken) word.classList.add('is-revealed');
    const wasActive = word.classList.contains('is-speaking');
    word.classList.toggle('is-speaking', active);
    if (active) word.setAttribute('aria-current', 'true');
    else word.removeAttribute('aria-current');
    if (active && !wasActive) word.scrollIntoView({ block: 'nearest', inline: 'nearest', behavior: 'smooth' });
  });
}
